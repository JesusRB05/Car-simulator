"""Build a mod index (docs/MODS.md section 6) from a folder of `.simmod` files.

The index is a static TOML document, so hosting it is a matter of putting one
file on a web server, a GitHub release or a network share. Each entry records
the digest and the size of the package, which is what the game checks before it
installs anything.

Only the standard library is used (Python 3.11+ for `tomllib`).

Examples
--------
    python tools/mod-index/generate.py builds/mods -o index.toml \\
        --base-url https://example.com/mods/
    python tools/mod-index/generate.py builds/mods -o index.toml \\
        --base-url file:///srv/mods/ --name "Team index"
"""

from __future__ import annotations

import argparse
import hashlib
import sys
import tomllib
import zipfile
from pathlib import Path


def quote(text: str) -> str:
    """A TOML basic string."""
    escaped = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
    return f'"{escaped}"'


def array(values: list[str]) -> str:
    return "[" + ", ".join(quote(value) for value in values) + "]"


def read_manifest(package: Path) -> dict:
    """The `mod.toml` inside a `.simmod` (a zip)."""
    with zipfile.ZipFile(package) as archive:
        names = [name for name in archive.namelist() if name.endswith("mod.toml")]
        if not names:
            raise ValueError("no mod.toml")
        # Prefer the shallowest manifest: a package may wrap everything in a
        # folder, as a GitHub export does.
        names.sort(key=lambda name: name.count("/"))
        text = archive.read(names[0]).decode("utf-8-sig")  # tolerate a BOM
        return tomllib.loads(text)


def entry_for(package: Path, base_url: str) -> dict:
    manifest = read_manifest(package)
    digest = hashlib.sha256(package.read_bytes()).hexdigest()
    name = package.name
    return {
        "id": manifest.get("id", ""),
        "version": manifest.get("version", ""),
        "download": base_url + name,
        "sha256": digest,
        "size": package.stat().st_size,
        "license": manifest.get("license", ""),
        "types": manifest.get("types", []),
        "changelog": manifest.get("changelog", ""),
        "dependencies": [
            f"{dependency['id']} {dependency.get('version', '*')}"
            if isinstance(dependency, dict)
            else str(dependency)
            for dependency in manifest.get("dependencies", [])
        ],
    }


def render(entries: list[dict], name: str, description: str) -> str:
    lines = [
        "# Generated by tools/mod-index/generate.py - do not edit by hand.",
        "",
        f"name = {quote(name)}",
    ]
    if description:
        lines.append(f"description = {quote(description)}")
    for entry in entries:
        lines += [
            "",
            "[[version]]",
            f"id = {quote(entry['id'])}",
            f"version = {quote(entry['version'])}",
            f"download = {quote(entry['download'])}",
            f"sha256 = {quote(entry['sha256'])}",
            f"size = {entry['size']}",
        ]
        if entry["license"]:
            lines.append(f"license = {quote(entry['license'])}")
        if entry["types"]:
            lines.append(f"types = {array(entry['types'])}")
        if entry["dependencies"]:
            lines.append(f"dependencies = {array(entry['dependencies'])}")
        if entry["changelog"]:
            lines.append(f"changelog = {quote(entry['changelog'])}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("packages", type=Path, help="folder with .simmod files")
    parser.add_argument("-o", "--output", type=Path, default=Path("index.toml"))
    parser.add_argument("--base-url", default="", help="prefix for the download URLs (a folder URL or path)")
    parser.add_argument("--name", default="Car Simulator mod index")
    parser.add_argument("--description", default="")
    args = parser.parse_args(argv)

    if not args.packages.is_dir():
        print(f"{args.packages}: not a directory", file=sys.stderr)
        return 2

    base_url = args.base_url
    if base_url and not base_url.endswith("/"):
        base_url += "/"

    entries: list[dict] = []
    failures = 0
    for package in sorted(args.packages.glob("*.simmod")):
        try:
            entry = entry_for(package, base_url)
        except (ValueError, KeyError, zipfile.BadZipFile, tomllib.TOMLDecodeError) as error:
            print(f"{package.name}: {error}", file=sys.stderr)
            failures += 1
            continue
        if not entry["id"] or not entry["version"]:
            print(f"{package.name}: mod.toml has no id or version", file=sys.stderr)
            failures += 1
            continue
        entries.append(entry)

    if not entries:
        print("no usable packages found", file=sys.stderr)
        return 1

    args.output.write_text(render(entries, args.name, args.description), encoding="utf-8")
    print(f"{args.output}: {len(entries)} package(s)")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
